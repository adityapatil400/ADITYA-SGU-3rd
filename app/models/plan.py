class DistributionPlan(Base):
    """
    Distribution plan generated by an external decision service
    and authoritatively evaluated, validated, and committed by the backend.
    
    CRITICAL ARCHITECTURAL CONSTRAINTS:
    - input_inventory_version records the exact inventory version used by the decision service.
    - Status transitions are guarded: candidates are advisory only and cannot alter stock
      until authoritative validation succeeds and commitment is executed.
    """

    __tablename__ = "distribution_plans"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    plan_code: Mapped[str] = mapped_column(String(64), unique=True, index=True, nullable=False)
    
    # Authoritative lifecycle status
    status: Mapped[PlanStatus] = mapped_column(
        SQLEnum(PlanStatus, name="plan_status_enum"),
        default=PlanStatus.PROPOSED,
        nullable=False,
        index=True
    )

    # Scoped warehouse target and optimistic version tracking
    target_warehouse_id: Mapped[Optional[int]] = mapped_column(
        Integer,
        ForeignKey("warehouses.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    scenario_id: Mapped[Optional[int]] = mapped_column(
        Integer,
        ForeignKey("seeded_scenarios.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    input_inventory_version: Mapped[int] = mapped_column(
        Integer,
        default=1,
        nullable=False,
        comment="Authoritative inventory version at the time decision candidate was generated."
    )

    # Traceability UUID linking all stages
    trace_id: Mapped[str] = mapped_column(
        String(64),
        default=lambda: str(uuid.uuid4()),
        index=True,
        nullable=False
    )

    # Raw candidate allocations from decision service (strictly uncommitted proposal)
    candidate_allocations: Mapped[list[Dict[str, Any]]] = mapped_column(JSON, default=list, nullable=False)

    # Decision service provenance metadata (model name, candidate ID, confidence score, parameters)
    decision_service_metadata: Mapped[Dict[str, Any]] = mapped_column(JSON, default=dict, nullable=False)

    # Backend authoritative validation results
    is_validated: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    validation_results: Mapped[Dict[str, Any]] = mapped_column(JSON, default=dict, nullable=False)
    validated_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # Authoritative commitment, approval, and creator details
    created_by_user_id: Mapped[Optional[int]] = mapped_column(
        Integer,
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    approved_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    approved_by_user_id: Mapped[Optional[int]] = mapped_column(
        Integer,
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    committed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    committed_by_user_id: Mapped[Optional[int]] = mapped_column(
        Integer,
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )

    # Relationships
    created_by_user: Mapped[Optional["User"]] = relationship(
        "User",
        foreign_keys=[created_by_user_id]
    )
    approved_by_user: Mapped[Optional["User"]] = relationship(
        "User",
        foreign_keys=[approved_by_user_id]
    )
    committed_by_user: Mapped[Optional["User"]] = relationship(
        "User",
        back_populates="committed_plans",
        foreign_keys=[committed_by_user_id]
    )

    allocations: Mapped[list["PlanAllocation"]] = relationship(
        "PlanAllocation",
        back_populates="plan",
        cascade="all, delete-orphan",
    )
    events: Mapped[list["PlanEvent"]] = relationship(
        "PlanEvent",
        back_populates="plan",
        cascade="all, delete-orphan",
    )
    scenario: Mapped[Optional["SeededScenario"]] = relationship(
        "SeededScenario",
        back_populates="plans"
    )
    reservations: Mapped[list["InventoryReservation"]] = relationship(
        "InventoryReservation",
        back_populates="plan",
    )

    # --------------------------------------------------------------------------
    # Authoritative Traceability Properties
    # --------------------------------------------------------------------------

    @property
    def plan_id(self) -> int:
        return self.id

    @property
    def inventory_version(self) -> int:
        return self.input_inventory_version

    @property
    def inventory_snapshot(self) -> Dict[str, Any]:
        if self.decision_service_metadata and "scenario_snapshot" in self.decision_service_metadata:
            return self.decision_service_metadata["scenario_snapshot"]
        return {}

    @property
    def validation_status(self) -> str:
        if self.status == PlanStatus.VALIDATED:
            return "VALIDATED"
        if self.status == PlanStatus.REJECTED:
            return "REJECTED"
        if self.is_validated:
            return "VALIDATED"
        if self.validation_results and "validation_status" in self.validation_results:
            return self.validation_results["validation_status"]
        return "PENDING"

    @property
    def rejection_reasons(self) -> list[str]:
        if not self.validation_results:
            return []
        if "rejection_reasons" in self.validation_results:
            return self.validation_results["rejection_reasons"]
        if "rejection_reason" in self.validation_results:
            return [self.validation_results["rejection_reason"]]
        violations = self.validation_results.get("violations", [])
        return [
            str(v["message"])
            for v in violations
            if isinstance(v, dict) and v.get("message") is not None
        ]

    @property
    def decision_service_status(self) -> str:
        if self.decision_service_metadata and "decision_service_status" in self.decision_service_metadata:
            return self.decision_service_metadata["decision_service_status"]
        if self.status == PlanStatus.FAILED:
            return "FAILED"
        return "COMPLETED" if self.candidate_allocations else "PENDING"

    @property
    def approval_status(self) -> str:
        if self.approved_by_user_id is not None or self.status in (PlanStatus.APPROVED, PlanStatus.COMMITTED):
            return "APPROVED"
        if self.status == PlanStatus.REJECTED:
            return "REJECTED"
        return "PENDING"

    @property
    def commitment_status(self) -> str:
        if self.status == PlanStatus.COMMITTED:
            return "COMMITTED"
        if self.status == PlanStatus.REJECTED:
            return "REJECTED"
        return "UNCOMMITTED"

    @property
    def audit_event_ids(self) -> list[int]:
        if not self.events:
            return []
        return [e.id for e in self.events if hasattr(e, "id")]


class PlanAllocation(Base):
    """
    Specific allocation line within a distribution plan transferring product units
    from an authoritative warehouse batch to a destination store.
    """

    __tablename__ = "plan_allocations"
    __table_args__ = (
        CheckConstraint("allocated_quantity > 0", name="chk_plan_alloc_qty_positive"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    plan_id: Mapped[int] = mapped_column(
        Integer,
        ForeignKey("distribution_plans.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    order_item_id: Mapped[Optional[int]] = mapped_column(
        Integer,
        ForeignKey("distribution_order_items.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    source_warehouse_id: Mapped[int] = mapped_column(
        Integer,
        ForeignKey("warehouses.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    destination_store_id: Mapped[int] = mapped_column(
        Integer,
        ForeignKey("stores.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    product_id: Mapped[int] = mapped_column(
        Integer,
        ForeignKey("products.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    batch_id: Mapped[Optional[int]] = mapped_column(
        Integer,
        ForeignKey("inventory_batches.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    allocated_quantity: Mapped[int] = mapped_column(Integer, nullable=False)
    allocation_status: Mapped[AllocationStatus] = mapped_column(
        SQLEnum(AllocationStatus, name="allocation_status_enum"),
        default=AllocationStatus.PROPOSED,
        nullable=False,
        index=True
    )
    estimated_transit_hours: Mapped[int] = mapped_column(Integer, default=24, nullable=False)

    # Relationships
    plan: Mapped["DistributionPlan"] = relationship("DistributionPlan", back_populates="allocations")
    order_item: Mapped[Optional["DistributionOrderItem"]] = relationship("DistributionOrderItem", back_populates="allocations")
    source_warehouse: Mapped["Warehouse"] = relationship("Warehouse", foreign_keys=[source_warehouse_id])
    destination_store: Mapped["Store"] = relationship("Store", foreign_keys=[destination_store_id])
    product: Mapped["Product"] = relationship("Product", back_populates="allocations")
    batch: Mapped[Optional["InventoryBatch"]] = relationship("InventoryBatch", back_populates="allocations")


class PlanEvent(Base):
    """
    Append-only immutable audit event ledger capturing all state transitions,
    authoritative rule checks, and approvals for complete operational traceability.
    """

    __tablename__ = "plan_events"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    plan_id: Mapped[int] = mapped_column(
        Integer,
        ForeignKey("distribution_plans.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    trace_id: Mapped[str] = mapped_column(String(64), index=True, nullable=False)
    event_type: Mapped[PlanEventType] = mapped_column(
        SQLEnum(PlanEventType, name="plan_event_type_enum"),
        nullable=False,
        index=True
    )
    actor_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        comment="e.g. 'decision_service', 'validation_engine', 'operator'"
    )
    actor_id: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    previous_status: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    new_status: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    payload: Mapped[Dict[str, Any]] = mapped_column(JSON, default=dict, nullable=False)

    # Relationship
    plan: Mapped["DistributionPlan"] = relationship("DistributionPlan", back_populates="events")


