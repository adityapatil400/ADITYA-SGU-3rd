class PlanStatus(str, enum.Enum):
    DRAFT = "DRAFT"                  # Initial scenario snapshot created
    GENERATED = "GENERATED"          # Candidate plan generated by decision service
    PROPOSED = "PROPOSED"            # Alias for candidate generation (backward compatibility)
    VALIDATING = "VALIDATING"        # Backend is executing authoritative rule checks
    VALIDATED = "VALIDATED"          # Passed authoritative validation checks; eligible for review
    APPROVED = "APPROVED"            # Authorized by independent approver (separation of duties)
    COMMITTED = "COMMITTED"          # Authoritatively executed and stock balance committed
    REJECTED = "REJECTED"            # Failed validation checks or business constraints
    CANCELLED = "CANCELLED"          # Plan cancelled by authorized operator
    FAILED = "FAILED"                # Decision service or technical failure


