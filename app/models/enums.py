import enum


class UserRole(str, enum.Enum):
    ADMIN = "ADMIN"        # Manages users, configuration, and access
    PLANNER = "PLANNER"    # Creates scenarios and candidate plans, requests validation
    APPROVER = "APPROVER"  # Reviews validated plans and authorizes commitment
    VIEWER = "VIEWER"      # Reads permitted inventory and plan information
    OPERATOR = "OPERATOR"  # Operational execution (backward compatibility)
    AUDITOR = "AUDITOR"    # Audit log inspection (backward compatibility)



