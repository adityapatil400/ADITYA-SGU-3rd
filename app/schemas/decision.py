from typing import List, Optional
from pydantic import BaseModel, Field
from app.models.enums import AllocationPriority


class ProposedMovement(BaseModel):
    """
    Individual movement proposed by an external AI or heuristic decision service.
    This is an unverified proposal and must be checked by the backend validation engine.
    """
    sku: str = Field(..., max_length=100, examples=["SKU-ELEC-402"])
    from_node_code: str = Field(..., max_length=50, examples=["DC-CENTRAL-01"])
    to_node_code: str = Field(..., max_length=50, examples=["STORE-MUMBAI-05"])
    quantity: int = Field(..., gt=0, examples=[250])
    priority: AllocationPriority = Field(default=AllocationPriority.NORMAL)
    estimated_transit_hours: int = Field(default=24, ge=1)
    rationale: Optional[str] = Field(default=None, description="AI reasoning for this movement")


class CandidatePlanProposal(BaseModel):
    """
    Candidate allocation plan generated by the decision service.
    
    IMPORTANT ARCHITECTURAL RULE:
    This payload represents a candidate proposal ONLY. It cannot commit inventory
    or bypass authoritative validation.
    """
    candidate_id: str = Field(..., examples=["CAND-AI-9021"])
    scenario_code: str = Field(..., examples=["SCENARIO-DIWALI-PEAK-2026"])
    model_version: str = Field(default="flowgrid-ai-v1.0")
    confidence_score: float = Field(..., ge=0.0, le=1.0, examples=[0.94])
    proposed_movements: List[ProposedMovement] = Field(default_factory=list)
